/**
 * Renders a crisp Lucide inline SVG string.
 * @param {keyof typeof ICON_PATHS} name
 * @param {{ size?: number, strokeWidth?: number, className?: string }} [opts]
 * @returns {string}
 */
export function renderIcon(name, { size = 14, strokeWidth = 1.75, className = '' } = {}) {
  const path = ICON_PATHS[name] || ICON_PATHS.activity;
  const cls = className ? `ui-icon ${className}` : 'ui-icon';
  return `<svg class="${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${path}</svg>`;
}

/**
 * Returns the semantic Lucide icon name for a device preset.
 */
export function getDeviceIconName(dev) {
  if (!dev) return 'smartphone';
  if (dev.iconName && ICON_PATHS[dev.iconName]) return dev.iconName;
  if (dev.type === 'mobile') return 'smartphone';
  if (dev.type === 'tablet') return 'tablet';
  if ((dev.name || '').toLowerCase().includes('laptop') || (dev.name || '').toLowerCase().includes('macbook')) {
    return 'laptop';
  }
  return 'monitor';
}
